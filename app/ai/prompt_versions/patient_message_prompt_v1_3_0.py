"""
Patient message prompt version: v1.3.0.
For changes, create a new version.

Drafts a plain-language clinical LETTER to a patient summarizing their lab
results. This is a SEPARATE LLM call from AI annotation/enrichment: separate
prompt, separate output schema, separate validation and provenance. It is
grounded in the validated, structured findings (de-identified allowlist) — NOT
by feeding the enrichment's free text back in as trusted ground truth.

The draft is always clinician-reviewed before any (demo) send. The model is
instructed never to include identifiers, a clinic name, or a clinician
signature — the patient's name, the clinic name and the signature are applied at
render time, never generated by the LLM.

v1.3.0 removes the `history_window_days` variable. Historical results were never
actually date-filtered — the query capped rows per analyte code, not by age — so
the "last N days" framing in the prompt text was misleading. The Service Layer
no longer caps history by count either; all prior results for the current
analytes are now included, so the prompt describes history as complete rather
than time-windowed.
"""

