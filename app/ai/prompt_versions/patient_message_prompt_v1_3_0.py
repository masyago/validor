# ---------------------------------------------------------------------------
# Current-results table with human-readable analyte names (message-specific).
# ---------------------------------------------------------------------------


class NamedObservationRow(BaseModel):
    """A single analyte result including its human-readable display name."""

    analyte_code: str
    display: str | None
    value: float | str
    unit: str | None
    reference_low: float | None = Field(default=None)
    reference_high: float | None = Field(default=None)
    flag: str  # NORMAL | LOW | HIGH | CRITICAL_LOW | CRITICAL_HIGH
    date: str  # effective_at


def format_named_results(observations: list[NamedObservationRow]) -> str:
    """Serialise results into a pipe-delimited table that includes the
    analyte's display name so the model can name findings in plain language."""
    header = (
        "analyte_code | name | value | unit | reference_low | "
        "reference_high | flag | date"
    )
    separator = "-" * len(header)
    rows = [header, separator]
    for obs in observations:
        name = obs.display or obs.analyte_code
        low = (
            str(obs.reference_low) if obs.reference_low is not None else "N/A"
        )
        high = (
            str(obs.reference_high)
            if obs.reference_high is not None
            else "N/A"
        )
        rows.append(
            f"{obs.analyte_code} | {name} | {obs.value} | {obs.unit} | "
            f"{low} | {high} | {obs.flag} | {obs.date}"
        )
    return "\n".join(rows)


